// Chat contract between the DFD frontend widgets and the EXTERNAL chatbot
// backend. This file defines shapes only — no LLM calls, no API keys, no AI
// logic lives in this repo. When NEXT_PUBLIC_CHAT_ENABLED is false (or the
// backend is unreachable) every widget falls back to deterministic local
// answers and human handoff. No fake AI, ever.

export const CHAT_ENABLED =
  process.env.NEXT_PUBLIC_CHAT_ENABLED === 'true';

export const CHAT_API_BASE =
  process.env.NEXT_PUBLIC_CHAT_API_URL || '';

// ---------------------------------------------------------------------------
// Intents the external backend must implement.
// ---------------------------------------------------------------------------

export type ChatIntentType =
  | 'create_lead'
  | 'create_order'
  | 'create_request'
  | 'portal_status'
  | 'handoff';

export interface ChatIntent {
  type: ChatIntentType;
  /** Free-form payload; validated server-side by the chatbot backend. */
  payload: Record<string, unknown>;
  /** Idempotency key generated by the widget for safe retries. */
  idempotencyKey: string;
}

export interface ChatIntentResult {
  ok: boolean;
  reply: string;
  /** Optional deep link, e.g. /client/dashboard after create_order. */
  link?: string;
  linkLabel?: string;
}

// ---------------------------------------------------------------------------
// Public context the backend may read (served by the Go API, consumed by the
// external chatbot backend — documented here so both sides agree).
//   GET /api/v1/public/chat/context  -> ChatContext
// ---------------------------------------------------------------------------

export interface ChatPackageBrief {
  slug: string;
  name: string;
  price: number;
  discountPrice: number | null;
  features: string[];
}

export interface ChatContext {
  packages: ChatPackageBrief[];
  faqs: { q: string; a: string }[];
  contact: { whatsapp: string; email: string; address: string };
}

// ---------------------------------------------------------------------------
// Widget-side message model (persisted to localStorage).
// ---------------------------------------------------------------------------

export type ChatRole = 'user' | 'bot';

export interface ChatMessageModel {
  id: string;
  role: ChatRole;
  text: string;
  at: number;
  link?: string;
  linkLabel?: string;
}

export const QUICK_REPLIES = [
  'Packages',
  'Pricing',
  'My project',
  'Talk to human',
] as const;

export function newIdempotencyKey(): string {
  if (typeof crypto !== 'undefined' && 'randomUUID' in crypto) {
    return crypto.randomUUID();
  }
  return `chat-${Date.now()}-${Math.floor(Math.random() * 1e9)}`;
}

export interface OfflineAnswerSet {
  pricing: string;
  project: string;
  human: string;
  duration: string;
  fallback: string;
}

// Deterministic offline answers. Used whenever the external backend is
// disabled or unreachable. These never pretend to be AI reasoning.
export function offlineAnswer(input: string, answers: OfflineAnswerSet): string {
  const q = input.toLowerCase();
  if (q.includes('pric') || q.includes('harga') || q.includes('cost') || q.includes('paket') || q.includes('package')) {
    return answers.pricing;
  }
  if (q.includes('track') || q.includes('lacak') || q.includes('status') || q.includes('order') || q.includes('proyek')) {
    return answers.project;
  }
  if (q.includes('human') || q.includes('admin') || q.includes('cs') || q.includes('whatsapp') || q.includes('wa') || q.includes('tim')) {
    return answers.human;
  }
  if (q.includes('lama') || q.includes('long') || q.includes('duration') || q.includes('waktu')) {
    return answers.duration;
  }
  return answers.fallback;
}
